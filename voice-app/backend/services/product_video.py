def _text(value, *, max_length: int = 4000) -> str:
    if value is None:
        return ""
    text = str(value).strip()
    return text[:max_length]


def _plain(value) -> str:
    """Lowercase, accent-free, punctuation-free form used for fuzzy matching."""
    decomposed = unicodedata.normalize("NFD", str(value or "").lower())
    stripped = "".join(ch for ch in decomposed if unicodedata.category(ch) != "Mn")
    return re.sub(r"[^a-z0-9]+", " ", stripped).strip()


def snap_clip_duration_seconds(duration_seconds: float | int | None) -> int:
    """Snap a requested clip length onto the lengths Veo actually produces.

    Same rule as ``video_veo_chrome._normalize_requested_duration``; reimplemented
    here so the product video flow never imports the Chrome automation module.
    """
    if not duration_seconds:
        return DEFAULT_CLIP_DURATION_SECONDS
    return min(CLIP_DURATION_CHOICES, key=lambda item: abs(item - float(duration_seconds)))


@dataclass(frozen=True)
class SegmentConfig:
    """Derived clip plan. ``target_duration_seconds`` is a goal, not a promise."""

    clip_count: int
    clip_duration_seconds: int
    derived_duration_seconds: int
    micro_scenes_per_prompt: int
    target_duration_seconds: int
    explicit: bool


def resolve_segment_config(project: DBProductVideoProject) -> SegmentConfig:
    """Return the real clip count and duration for a project.

    Mirrors ``video_phase2._resolve_prompt_segment_config`` but always resolves to
    a concrete plan, because a product video always has a target duration.
    """
    target = max(1, int(getattr(project, "target_duration_seconds", None) or 30))
    configured = (
        getattr(project, "prompt_segment_count", None),
        getattr(project, "prompt_segment_duration_seconds", None),
        getattr(project, "micro_scenes_per_prompt", None),
    )
    if all(value is not None and int(value) > 0 for value in configured):
        clip_duration = snap_clip_duration_seconds(int(configured[1] or 0))
        clip_count = max(1, min(MAX_SHOT_COUNT, int(configured[0] or 1)))
        return SegmentConfig(
            clip_count=clip_count,
            clip_duration_seconds=clip_duration,
            derived_duration_seconds=clip_count * clip_duration,
            micro_scenes_per_prompt=max(1, int(configured[2] or DEFAULT_MICRO_SCENES_PER_PROMPT)),
            target_duration_seconds=target,
            explicit=True,
        )
    clip_duration = snap_clip_duration_seconds(getattr(project, "prompt_segment_duration_seconds", None))
    clip_count = max(1, min(MAX_SHOT_COUNT, math.ceil(target / clip_duration)))
    return SegmentConfig(
        clip_count=clip_count,
        clip_duration_seconds=clip_duration,
        derived_duration_seconds=clip_count * clip_duration,
        micro_scenes_per_prompt=max(
            1, int(getattr(project, "micro_scenes_per_prompt", None) or DEFAULT_MICRO_SCENES_PER_PROMPT)
        ),
        target_duration_seconds=target,
        explicit=False,
    )


def timeline_label(shot_order: int, clip_duration_seconds: int) -> str:
    start = max(0, (int(shot_order) - 1)) * int(clip_duration_seconds)
    return f"{start}-{start + int(clip_duration_seconds)}s"


