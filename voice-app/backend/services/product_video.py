def _speech_views(project: DBProductVideoProject, shot: DBProductVideoShot) -> tuple[SimpleNamespace, SimpleNamespace]:
    """Duck-typed views so ``video_speech`` can be reused without being modified.

    ``build_veo_native_speech_section`` expects ``VideoProject``/``VideoShot`` rows;
    product video rows carry the same information under different names and have no
    series, so the series lookups resolve to empty.
    """
    project_view = SimpleNamespace(
        id=project.id,
        target_language=project.target_language,
        dialogue_mode=project.dialogue_mode,
        series_id=None,
        retention_plan_json=None,
    )
    shot_view = SimpleNamespace(
        speech_cues_json=None,
        english_narration=shot.narration_text,
        retention_json=None,
        vietnamese_description=None,
        primary_action=shot.subject_motion,
        environment_motion=shot.environment_motion,
    )
    return project_view, shot_view


def build_speech_section(project: DBProductVideoProject, shot: DBProductVideoShot, db: Session) -> str:
    """Vietnamese spoken-dialogue block, inserted at prompt time (not clip time)."""
    if video_language.normalize_video_language(project.target_language) != video_speech.VEO_NATIVE_LANGUAGE:
        return ""
    project_view, shot_view = _speech_views(project, shot)
    section = video_speech.build_veo_native_speech_section(project_view, shot_view, db)
    if not section:
        return ""
    return f"{section}\n{VIETNAMESE_SPEECH_LENGTH_RULE}"


def build_prompt_text(
    shot: DBProductVideoShot,
    project: DBProductVideoProject,
    *,
    db: Session | None = None,
    config: SegmentConfig | None = None,
) -> str:
    """Assemble one Flow-ready prompt.

    Same label shape as ``video_phase2._prompt_text`` (``video_phase2.py:3608``) so the
    three note lines and the three separate motion lines stay comparable, plus the
    fixed product fidelity and product motion sections this flow adds.
    """
    resolved = config or resolve_segment_config(project)
    aspect_ratio = project.aspect_ratio
    clip_duration = int(shot.duration_seconds or resolved.clip_duration_seconds)
    header = [
        f"Create a {clip_duration}-second {aspect_ratio} live-action product video clip.",
        (
            f"This is clip {shot.shot_order} of {resolved.clip_count} of a "
            f"{resolved.derived_duration_seconds}-second product video covering timeline "
            f"{timeline_label(shot.shot_order, resolved.clip_duration_seconds)}."
        ),
        (
            "Product reference: use the attached product image (Flow Ingredients / References to Video) as "
            "the single source of truth for the product's shape, colour and label."
        ),
        (
            f"Segment structure: build {resolved.micro_scenes_per_prompt} connected micro-scenes inside this "
            "one clip, all serving one primary visual action."
        ),
    ]
    if shot.shot_order == 1 and _text(project.hook_text):
        header.append(f"Hook for the first 0-2 seconds: {_text(project.hook_text, max_length=1000)}")

    parts = [
        "\n".join(header),
        "",
        f"Video language: {video_language.video_language_english_name(project.target_language)}",
        f"Aspect ratio: {aspect_ratio}",
        f"Clip length: {clip_duration} seconds",
        f"Timeline position: {timeline_label(shot.shot_order, resolved.clip_duration_seconds)}",
        f"Beat role: {_text(shot.beat_role) or DEFAULT_BEAT_FRAMEWORK[0]}",
        f"Shot type: {_text(shot.shot_type) or PRODUCT_SHOT_TYPES[0]}",
        f"Camera angle: {_text(shot.camera_angle)}",
        f"Framing: {_text(shot.framing)}",
        f"Composition: {_text(shot.composition)}",
        f"Camera movement: {_text(shot.camera_motion)}",
        f"Subject motion: {_text(shot.subject_motion)}",
        f"Environment motion: {_text(shot.environment_motion)}",
        f"Lighting: {_text(shot.lighting)}",
        f"Mood: {_text(shot.mood)}",
        f"Visual style: {style_summary(project)}",
        f"Narration: {_text(shot.narration_text)}",
        f"Retention notes: {_text(shot.retention_notes) or _fallback_retention_notes(_text(shot.beat_role) or DEFAULT_BEAT_FRAMEWORK[0], shot.shot_order)}",
        f"Transition notes: {_text(shot.transition_notes) or _fallback_transition_notes(shot.shot_order)}",
        f"Sound design notes: {_text(shot.sound_design_notes) or _fallback_sound_design_notes(project)}",
        "",
        PRODUCT_FIDELITY_SECTION,
        "",
        MOTION_CONSTRAINT_SECTION,
    ]
    speech_section = build_speech_section(project, shot, db) if db is not None else ""
    if speech_section:
        parts.extend(["", speech_section])
    parts.extend(["", "Negative prompt:", DEFAULT_NEGATIVE_PROMPT])
    return "\n".join(part for part in parts if part is not None).strip() + "\n"


def generate_prompt_pack(project_id: str, db: Session) -> models.ProductVideoPromptPackResponse | None:
    """Build and store the prompt pack, enforcing the motion and variety rules first."""
    project = get_project_row(project_id, db)
    if project is None:
        return None
    shots = ordered_shots(project_id, db)
    if not shots:
        raise ProductVideoValidationError("Cần lập kế hoạch shot trước khi sinh prompt.")
    config = resolve_segment_config(project)

    for shot in shots:
        # Keep the closed vocabulary invariant even when a previously saved
        # plan (or a hand-edited database row) contains an LLM-invented value.
        shot.shot_type = normalize_shot_type(shot.shot_type)
        validate_motion_budget(shot, project)
    enforce_shot_variety(shots)

    db.query(DBProductVideoShotPrompt).filter(DBProductVideoShotPrompt.project_id == project_id).delete()
    rows: list[DBProductVideoShotPrompt] = []
    for shot in shots:
        row = DBProductVideoShotPrompt(
            project_id=project_id,
            shot_id=shot.id,
            prompt=build_prompt_text(shot, project, db=db, config=config),
            negative_prompt=DEFAULT_NEGATIVE_PROMPT,
            prompt_explanation_vi=_text(shot.retention_notes, max_length=2000) or None,
            aspect_ratio=project.aspect_ratio,
        )
        rows.append(row)
        db.add(row)
    _sync_render_bridge(project, db)
    project.status = "prompts_ready"
    project.planning_status = "prompts_ready"
    project.planning_error = None
    project.updated_at = datetime.utcnow()
    db.commit()
    for row in rows:
        db.refresh(row)
    order_by_shot = {shot.id: shot.shot_order for shot in shots}
    return models.ProductVideoPromptPackResponse(
        project_id=project.id,
        aspect_ratio=project.aspect_ratio,
        target_language=project.target_language,
        derived_clip_count=config.clip_count,
        derived_clip_duration_seconds=config.clip_duration_seconds,
        derived_duration_seconds=config.derived_duration_seconds,
        hook_text=project.hook_text,
        prompts=[_prompt_response(row, order_by_shot.get(row.shot_id, 0) or 0) for row in rows],
    )


