def _slug(value: str) -> str:
    plain = _plain(value)
    return re.sub(r"\s+", "-", plain).strip("-")[:60] or "product-video"


def get_prompt_pack_download(project_id: str, db: Session) -> tuple[str, str] | None:
    """Return ``(filename, content)`` with one labelled section per shot."""
    project = get_project_row(project_id, db)
    if project is None:
        return None
    shots = {shot.id: shot for shot in ordered_shots(project_id, db)}
    rows = ordered_prompts(project_id, db)
    if not rows:
        return None
    config = resolve_segment_config(project)
    blocks = [
        f"# Prompt pack — {project.title}",
        f"Chủ đề: {project.topic}",
        f"Tỉ lệ khung hình: {project.aspect_ratio}",
        f"Ngôn ngữ nội dung: {video_language.video_language_prompt_label(project.target_language)}",
        (
            f"Kế hoạch clip: {config.clip_count} clip × {config.clip_duration_seconds}s "
            f"= {config.derived_duration_seconds}s (mục tiêu {config.target_duration_seconds}s)"
        ),
        f"Hook: {_text(project.hook_text) or '(chưa có)'}",
    ]
    for index, row in enumerate(rows, start=1):
        shot = shots.get(row.shot_id)
        order = getattr(shot, "shot_order", index) or index
        beat = _text(getattr(shot, "beat_role", None)) or "-"
        shot_type = _text(getattr(shot, "shot_type", None)) or "-"
        blocks.append(
            "\n".join(
                [
                    "",
                    "=" * 72,
                    f"Shot {order}/{len(rows)} — beat: {beat} — shot type: {shot_type} — "
                    f"timeline {timeline_label(order, config.clip_duration_seconds)}",
                    "=" * 72,
                    "",
                    row.prompt.strip(),
                ]
            )
        )
    filename = f"product-video-prompt-pack-{_slug(project.title)}.txt"
    return filename, "\n".join(blocks).strip() + "\n"
