def is_blank_motion(value: str | None) -> bool:
    """Whether a motion field is effectively empty."""
    plain = _plain(value)
    return plain in BLANK_MOTION_VALUES


def non_blank_motion_count(shot) -> int:
    return sum(1 for field in MOTION_FIELDS if not is_blank_motion(getattr(shot, field, None)))


def style_summary(project) -> str:
    # Keep the user's edited style intact. Truncating at 400 characters can
    # split a sentence (or even leave a single stray character) in the
    # Flow-ready prompt, which makes the visual-style section look corrupted.
    style = _text(getattr(project, "visual_style", None), max_length=2000)
    if style:
        return style
    preset = _text(getattr(project, "visual_style_preset", None), max_length=40)
    if preset and preset != "custom":
        return preset.replace("_", " ")
    return "clean commercial product footage"


def environment_motion_from_style(project) -> str:
    """Fallback ambient motion, derived from the project's own visual style."""
    return (
        "continuous ambient motion in the environment that matches the stated visual style "
        f"({style_summary(project)}): moving light and soft shadows, drifting dust or steam, "
        "gently moving fabric, plants or background people, so the frame is never frozen"
    )


DEFAULT_CAMERA_MOTION = (
    "slow steady push-in on a gimbal that keeps the labelled face of the product parallel to the lens"
)


def validate_motion_budget(shot, project=None) -> bool:
    """Guarantee at least 2 of 3 motion fields are non-blank; fill in if not.

    Returns ``True`` when the shot had to be corrected. Fills ``environment_motion``
    from the project's visual style first, then ``camera_motion`` if still short.
    """
    changed = False
    if non_blank_motion_count(shot) >= MIN_NON_BLANK_MOTION_FIELDS:
        return changed
    if is_blank_motion(getattr(shot, "environment_motion", None)):
        shot.environment_motion = environment_motion_from_style(project)
        changed = True
    if non_blank_motion_count(shot) < MIN_NON_BLANK_MOTION_FIELDS and is_blank_motion(
        getattr(shot, "camera_motion", None)
    ):
        shot.camera_motion = DEFAULT_CAMERA_MOTION
        changed = True
    return changed


def enforce_shot_variety(shots: list) -> int:
    """Stop two consecutive shots sharing both ``shot_type`` and ``framing``."""
    changes = 0
    for index in range(1, len(shots)):
        previous = shots[index - 1]
        current = shots[index]
        same_type = _plain(getattr(current, "shot_type", None)) == _plain(getattr(previous, "shot_type", None))
        same_framing = _plain(getattr(current, "framing", None)) == _plain(getattr(previous, "framing", None))
        if not (same_type and same_framing):
            continue
        previous_framing = _plain(getattr(previous, "framing", None))
        replacement = next(
            (choice for choice in PRODUCT_FRAMING_CHOICES if _plain(choice) != previous_framing),
            PRODUCT_FRAMING_CHOICES[0],
        )
        current.framing = replacement
        changes += 1
    return changes


