def normalize_shot_type(value: str | None, *, default: str = "hero shot") -> str:
    """Force any value onto the closed vocabulary, never storing an invented one."""
    plain = _plain(value)
    if not plain:
        return default
    exact = _SHOT_TYPE_BY_PLAIN.get(plain)
    if exact:
        return exact
    for keyword, canonical in _SHOT_TYPE_KEYWORDS:
        if keyword in plain:
            return canonical
    close = difflib.get_close_matches(plain, list(_SHOT_TYPE_BY_PLAIN), n=1, cutoff=0.4)
    if close:
        return _SHOT_TYPE_BY_PLAIN[close[0]]
    return default


def beat_roles_for_shot_count(shot_count: int) -> list[str]:
    """Stretch ``DEFAULT_BEAT_FRAMEWORK`` over the actual clip count."""
    count = max(0, int(shot_count or 0))
    if count == 0:
        return []
    if count == 1:
        return [DEFAULT_BEAT_FRAMEWORK[0]]
    total = len(DEFAULT_BEAT_FRAMEWORK)
    roles = [
        DEFAULT_BEAT_FRAMEWORK[min(total - 1, round(index * (total - 1) / (count - 1)))]
        for index in range(count)
    ]
    roles[0] = DEFAULT_BEAT_FRAMEWORK[0]
    roles[-1] = DEFAULT_BEAT_FRAMEWORK[-1]
    return roles


