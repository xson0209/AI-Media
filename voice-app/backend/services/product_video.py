def _shot_planning_prompt(project: DBProductVideoProject, config: SegmentConfig, beat_roles: list[str]) -> str:
    context = "\n".join(_project_context_lines(project, config))
    beat_lines = "\n".join(
        f"- Clip {index + 1} ({timeline_label(index + 1, config.clip_duration_seconds)}): beat = {role}"
        for index, role in enumerate(beat_roles)
    )
    shot_type_list = ", ".join(f"`{value}`" for value in PRODUCT_SHOT_TYPES)
    framing_list = ", ".join(f"`{value}`" for value in PRODUCT_FRAMING_CHOICES)
    return f"""
Bạn là Product Video Prompt Studio trong Voicebox. Nhiệm vụ: lập kế hoạch shot cho một video bán sản phẩm
sẽ được sinh clip bằng Google Flow, với ảnh sản phẩm thật do người dùng tự đính kèm trong Flow.

{context}

Khung beat bắt buộc (mỗi clip một beat, đã tính sẵn):
{beat_lines}

Yêu cầu bắt buộc:
- Trả về đúng {config.clip_count} shot, `shot_order` từ 1 đến {config.clip_count}, không thừa không thiếu.
- `shot_type` CHỈ được lấy từ danh sách đóng này, viết y nguyên: {shot_type_list}. Không được tự phát minh giá trị khác.
- `framing` nên lấy từ: {framing_list}. Hai shot liên tiếp không được trùng cả `shot_type` lẫn `framing`.
- Mỗi shot phải có tối thiểu 2 trong 3 field `camera_motion`, `subject_motion`, `environment_motion` mô tả
  chuyển động thật. Không được viết `none`, `n/a`, `static`, `no motion` hay để trống để lách yêu cầu này.
- Sản phẩm ĐƯỢC nâng, mang đi, nghiêng nhẹ và được tay người tương tác. Chỉ tránh: quay tròn hết một vòng,
  spin nhanh, để nhãn rời khỏi khung rồi quay lại, và cho sản phẩm đi qua vật che.
- `retention_notes`, `transition_notes`, `sound_design_notes` bắt buộc không rỗng cho mọi shot, mỗi field một
  câu cụ thể cho đúng shot đó, không viết chung chung lặp lại.
- `narration_text` là lời nói người xem nghe được, viết bằng {video_language.video_language_english_name(project.target_language)}.
  Độ dài vừa đúng {config.clip_duration_seconds} giây nói bình thường (khoảng 18-20 chữ cho clip 8 giây).
- `hook_text` là câu/hình mở đầu cho 0-2 giây đầu của clip 1, phải cụ thể và gây tò mò.
- `prompt_explanation_vi` viết bằng tiếng Việt, giải thích ngắn cho người dùng biết shot đó làm gì.
- KHÔNG mô tả subtitle, caption, text overlay, logo hay watermark trong bất kỳ field nào.
- {video_language.viewer_language_instruction(project.target_language)}
- Trả về đúng JSON theo schema, không thêm markdown.
""".strip()


def _fallback_retention_notes(beat_role: str, shot_order: int) -> str:
    return (
        f"Retention role: shot {shot_order} carries the `{beat_role}` beat — introduce one clear visual "
        "change in the first second and leave one open question that the next clip answers."
    )


def _fallback_transition_notes(shot_order: int) -> str:
    return (
        f"Transition: cut out of shot {shot_order} on the product movement so the next clip starts on the "
        "matching action; keep continuity risk low."
    )


def _fallback_sound_design_notes(project: DBProductVideoProject) -> str:
    return (
        "Sound: keep room ambience plus one short tactile product SFX under the voice; music stays low so "
        f"the {video_language.video_language_english_name(project.target_language)} narration stays intelligible."
    )


def _apply_plan_to_shot(
    shot: DBProductVideoShot,
    item: ProductShotPlan,
    *,
    project: DBProductVideoProject,
    config: SegmentConfig,
    beat_role: str,
) -> None:
    shot.shot_order = item.shot_order
    shot.beat_role = beat_role
    shot.duration_seconds = config.clip_duration_seconds
    shot.shot_type = normalize_shot_type(item.shot_type)
    shot.framing = _text(item.framing, max_length=160) or PRODUCT_FRAMING_CHOICES[3]
    shot.camera_angle = _text(item.camera_angle, max_length=160) or "eye level"
    shot.composition = _text(item.composition, max_length=1200) or None
    shot.camera_motion = _text(item.camera_motion, max_length=1200) or None
    shot.subject_motion = _text(item.subject_motion, max_length=1200) or None
    shot.environment_motion = _text(item.environment_motion, max_length=1200) or None
    shot.lighting = _text(item.lighting, max_length=1200) or None
    shot.mood = _text(item.mood, max_length=600) or None
    shot.narration_text = _text(item.narration_text, max_length=2000) or None
    shot.retention_notes = _text(item.retention_notes, max_length=2000) or _fallback_retention_notes(
        beat_role, item.shot_order
    )
    shot.transition_notes = _text(item.transition_notes, max_length=2000) or _fallback_transition_notes(
        item.shot_order
    )
    shot.sound_design_notes = _text(item.sound_design_notes, max_length=2000) or _fallback_sound_design_notes(
        project
    )
    validate_motion_budget(shot, project)


def plan_shots(project_id: str, db: Session) -> list[models.ProductVideoShotResponse] | None:
    """Plan one shot per Flow clip, with a closed shot-type vocabulary and beat roles."""
    project = get_project_row(project_id, db)
    if project is None:
        return None
    config = resolve_segment_config(project)
    beat_roles = beat_roles_for_shot_count(config.clip_count)
    prompt = _shot_planning_prompt(project, config, beat_roles)

    project.planning_status = "running"
    project.planning_error = None
    db.commit()
    try:
        payload = _run_structured_codex(
            project, prompt, PRODUCT_VIDEO_PLAN_SCHEMA, step_name="product_video_shots", db=db
        )
        plan = ProductVideoPlan.model_validate(payload)
    except ValidationError as exc:
        project.planning_status = "failed"
        project.planning_error = "AI trả về kế hoạch shot không đúng định dạng."
        db.commit()
        video_errors.log_error(
            "Invalid product video shot plan",
            exc=exc,
            project_id=project.id,
            step_name="product_video_shots",
        )
        raise VideoPlanningValidationError("AI trả về kế hoạch shot không đúng định dạng. Thử lại.") from exc
    except Exception as exc:
        project.planning_status = "failed"
        project.planning_error = _text(str(exc), max_length=2000)
        db.commit()
        raise

    items = sorted(plan.shots, key=lambda item: item.shot_order)[: config.clip_count]
    db.query(DBProductVideoShotPrompt).filter(DBProductVideoShotPrompt.project_id == project_id).delete()
    db.query(DBProductVideoShot).filter(DBProductVideoShot.project_id == project_id).delete()
    shots: list[DBProductVideoShot] = []
    for index, item in enumerate(items):
        item.shot_order = index + 1
        shot = DBProductVideoShot(project_id=project_id)
        _apply_plan_to_shot(
            shot,
            item,
            project=project,
            config=config,
            beat_role=beat_roles[index] if index < len(beat_roles) else DEFAULT_BEAT_FRAMEWORK[-1],
        )
        shots.append(shot)
        db.add(shot)
    enforce_shot_variety(shots)

    project.hook_text = _text(plan.hook_text, max_length=1000) or project.hook_text
    project.retention_plan_json = {"review_vi": _text(plan.retention_plan_vi, max_length=4000)}
    project.sound_design_plan_json = {"review_vi": _text(plan.sound_design_plan_vi, max_length=4000)}
    project.planning_status = "shots_ready"
    project.status = "shots_ready"
    project.updated_at = datetime.utcnow()
    _sync_render_bridge(project, db)
    db.commit()
    return [models.ProductVideoShotResponse.model_validate(shot) for shot in ordered_shots(project_id, db)]


