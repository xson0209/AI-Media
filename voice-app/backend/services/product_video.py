def _run_structured_codex(project: DBProductVideoProject, prompt: str, schema: dict, *, step_name: str, db: Session) -> dict:
    """Single-attempt structured Codex call scoped to the product video workflow.

    Reduced form of ``video_phase2._run_structured_codex``: no ``video_observability``
    logging, because those rows have a foreign key onto ``video_projects``.
    """
    settings = settings_service.get_ai_planning_settings(db)
    timeout_seconds = max(5, min(settings.timeout_seconds or CODEX_TIMEOUT_SECONDS, CODEX_TIMEOUT_SECONDS))
    with video_planning_pool.planning_slot(
        db,
        work_key=f"product_video:{project.id}",
        workflow_type="product_video",
        step_name=step_name,
        provider=settings.provider,
        model=settings.model,
        details={"prompt_chars": len(prompt), "timeout_seconds": timeout_seconds},
    ):
        raw = ai_planning.run_codex_exec(settings, prompt, output_schema=schema, timeout_seconds=timeout_seconds)
        try:
            return _load_json_object(raw)
        except VideoPlanningValidationError as exc:
            video_errors.log_error(
                "Product video planning output failed JSON validation",
                exc=exc,
                project_id=project.id,
                step_name=step_name,
                output_chars=len(raw or ""),
            )
            raise


