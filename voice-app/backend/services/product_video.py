def _delete_bridge_shot(shot: DBVideoShot, db: Session) -> None:
    clips = db.query(DBVideoShotClip).filter(DBVideoShotClip.shot_id == shot.id).all()
    for clip in clips:
        video_storage.remove_artifact_file(clip.file_path)
    db.query(DBVideoShotClip).filter(DBVideoShotClip.shot_id == shot.id).delete(synchronize_session=False)
    db.query(DBVideoShotPrompt).filter(DBVideoShotPrompt.shot_id == shot.id).delete(synchronize_session=False)
    db.delete(shot)


def _sync_render_bridge(project: DBProductVideoProject, db: Session) -> DBVideoProject:
    """Synchronize Product Video rows into the shared phase-2 render model."""
    bridge_id = project.render_project_id or str(uuid.uuid4())
    bridge = db.query(DBVideoProject).filter(DBVideoProject.id == bridge_id).first()
    bridge_was_existing = bridge is not None
    bridge_config = _bridge_config(project)
    changed = not bridge_was_existing
    if bridge is None:
        bridge = DBVideoProject(id=bridge_id, **bridge_config)
        db.add(bridge)
        project.render_project_id = bridge_id
        db.flush()
    else:
        for key, value in bridge_config.items():
            if getattr(bridge, key, None) != value:
                changed = True
            setattr(bridge, key, value)
        project.render_project_id = bridge.id

    product_shots = ordered_shots(project.id, db)
    existing_by_order = {
        int(row.shot_order): row
        for row in db.query(DBVideoShot)
        .filter(DBVideoShot.project_id == bridge.id)
        .order_by(DBVideoShot.shot_order.asc())
        .all()
    }
    seen_orders: set[int] = set()
    for product_shot in product_shots:
        order = int(product_shot.shot_order)
        seen_orders.add(order)
        render_shot = existing_by_order.pop(order, None)
        values = _bridge_shot_values(product_shot, project)
        if render_shot is None:
            render_shot = DBVideoShot(project_id=bridge.id, shot_order=order, **values)
            db.add(render_shot)
            changed = True
        else:
            for key, value in values.items():
                if getattr(render_shot, key, None) != value:
                    changed = True
                setattr(render_shot, key, value)

    for stale_shot in existing_by_order.values():
        _delete_bridge_shot(stale_shot, db)
        changed = True

    db.flush()

    product_prompts = {row.shot_id: row for row in ordered_prompts(project.id, db)}
    bridge_shots = (
        db.query(DBVideoShot)
        .filter(DBVideoShot.project_id == bridge.id)
        .order_by(DBVideoShot.shot_order.asc())
        .all()
    )
    bridge_prompts = {
        row.shot_id: row
        for row in db.query(DBVideoShotPrompt).filter(DBVideoShotPrompt.project_id == bridge.id).all()
    }
    for render_shot in bridge_shots:
        product_shot = next((item for item in product_shots if item.shot_order == render_shot.shot_order), None)
        product_prompt = product_prompts.get(product_shot.id) if product_shot else None
        existing_prompt = bridge_prompts.pop(render_shot.id, None)
        if product_prompt is None:
            if existing_prompt is not None:
                db.delete(existing_prompt)
                changed = True
            render_shot.prompt_status = "missing"
            continue
        prompt_values = {
            "project_id": bridge.id,
            "shot_id": render_shot.id,
            "version": 1,
            "prompt": product_prompt.prompt,
            "prompt_explanation_vi": product_prompt.prompt_explanation_vi,
            "negative_prompt": product_prompt.negative_prompt,
            "duration_seconds": render_shot.duration_seconds,
            "aspect_ratio": product_prompt.aspect_ratio,
            "camera_motion": render_shot.camera_motion,
            "subject_motion": render_shot.subject_motion,
            "environment_motion": render_shot.environment_motion,
            "retention_notes": product_shot.retention_notes if product_shot else None,
            "transition_notes": product_shot.transition_notes if product_shot else None,
            "sound_design_notes": product_shot.sound_design_notes if product_shot else None,
        }
        if existing_prompt is None:
            db.add(DBVideoShotPrompt(id=str(uuid.uuid4()), **prompt_values))
            changed = True
        else:
            for key, value in prompt_values.items():
                if getattr(existing_prompt, key, None) != value:
                    changed = True
                setattr(existing_prompt, key, value)
        render_shot.prompt_status = "completed"

    for stale_prompt in bridge_prompts.values():
        db.delete(stale_prompt)
        changed = True

